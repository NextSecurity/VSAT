<#
.SYNOPSIS
    Records CIS Benchmark mappings reviewed by a licensed reviewer (bring your license; maintainer-side).
.DESCRIPTION
    VSAT ships no CIS mappings of its own. A reviewer who holds the licensed CIS Benchmark exports a CSV
    with the columns recommendation,ruleId,relation from their review, and this script turns it into
    reviewed ("verified") rows with reviewer, date, edition and source reference, ready for
    build/New-CrosswalkSeed.ps1 (put the output in build/crosswalk/imported/).

    Only recommendation numbers are written; never titles or benchmark text. The CSV and the benchmark
    itself are never committed. The script refuses to run without -SourceEdition.
.EXAMPLE
    pwsh ./build/Import-CisMapping.ps1 -CsvPath ./review.csv -Framework cis-esxi-8 -FrameworkName 'CIS VMware ESXi 8.0 Benchmark' `
        -SourceEdition v1.2.0 -Reviewer 'J. Doe (CIS SecureSuite member)' -ReviewedUtc 2026-10-01 -Out ./build/crosswalk/imported/cis-esxi-8.json
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$CsvPath,
    [Parameter(Mandatory)][string]$Framework,
    [Parameter(Mandatory)][string]$Reviewer,
    [Parameter(Mandatory)][string]$ReviewedUtc,
    [Parameter(Mandatory)][string]$Out,
    [string]$FrameworkName,
    [string]$SourceEdition
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $SourceEdition) { throw 'Refusing to import CIS mappings without -SourceEdition (the licensed benchmark edition the review used, e.g. v1.2.0).' }
if ($Framework -notmatch '^cis-[a-z0-9.-]+$') { throw "Framework id must start with 'cis-' (got '$Framework')." }
if ($ReviewedUtc -notmatch '^\d{4}-\d{2}-\d{2}') { throw "ReviewedUtc must be yyyy-MM-dd (got '$ReviewedUtc')." }

$ids = @{}
foreach ($f in Get-ChildItem -LiteralPath (Join-Path $root 'rules') -Filter '*.json') {
    if ($f.Name -eq 'pack.json') { continue }
    foreach ($r in @(([IO.File]::ReadAllText($f.FullName) | ConvertFrom-Json -AsHashtable).rules)) { $ids[$r.id] = $true }
}
$name = if ($FrameworkName) { $FrameworkName } else { $Framework }
$rows = @(Import-Csv -LiteralPath $CsvPath)
$mappings = foreach ($row in $rows) {
    $rid = ([string]$row.ruleId).Trim(); $rec = ([string]$row.recommendation).Trim()
    $rel = if ($row.relation) { ([string]$row.relation).Trim() } else { 'supports' }
    if (-not $ids.ContainsKey($rid)) { Write-Warning "Skipping unknown VSAT rule '$rid' (recommendation $rec)"; continue }
    if ($rec -notmatch '^\d+(\.\d+)*$') { Write-Warning "Skipping recommendation '$rec' for $rid (expected a number such as 1.2.3)"; continue }
    if ($rel -notin @('equivalent', 'subset', 'supports')) { throw "Relation '$rel' for $rid is not equivalent, subset or supports." }
    [ordered]@{ ruleId = $rid; framework = $Framework; control = $rec; relation = $rel; status = 'verified'; basis = 'licensed reviewer confirmed against the benchmark'; reviewer = $Reviewer; reviewedUtc = $ReviewedUtc; sourceRef = "$name $SourceEdition" }
}
$doc = [ordered]@{
    notes = 'Generated by build/Import-CisMapping.ps1 from a licensed review. Recommendation numbers only; no CIS text.'
    framework = [ordered]@{ id = $Framework; name = $name; edition = $SourceEdition; publisher = 'Center for Internet Security'; license = 'licensed-ids-only'; url = 'https://www.cisecurity.org/cis-benchmarks' }
    mappings = @($mappings | Sort-Object { $_.ruleId }, { $_.control } -Culture ([Globalization.CultureInfo]::InvariantCulture))
}
$dir = Split-Path -Parent ([IO.Path]::GetFullPath($Out))
if (-not (Test-Path -LiteralPath $dir)) { [void](New-Item -ItemType Directory -Path $dir -Force) }
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Out), (($doc | ConvertTo-Json -Depth 6).Replace("`r`n", "`n") + "`n"), [Text.UTF8Encoding]::new($false))
Write-Host ("Wrote {0}: {1} reviewed mapping(s) for {2} {3}" -f $Out, @($doc.mappings).Count, $name, $SourceEdition)
